"""Phase 4 (Commercial setup), core step "Set the price and policies".

Pricing: VentureLab has no evidence of willingness to pay, so it proposes price
*hypotheses* (labelled ASSUMPTION) and the experiment that would test them. The founder
chooses one; the choice is a recorded, fingerprint-bound founder approval, never a
model decision. No payment of any kind is set up.

Policies: plain-language DRAFT terms, privacy and refund policies built from the brief.
They are not legal advice and must be reviewed by a qualified professional before use.
"""
from __future__ import annotations

from builder_models import check_content

DRAFT_BANNER = ("DRAFT — generated by VentureLab for founder review. Not legal advice; have it "
                "reviewed by a qualified professional before publishing.")

# Hypothesis grid, not market data: a free core plus three test prices for a paid tier.
TEST_PRICES_EUR = (4, 8, 15)


def pricing_hypotheses(brief: dict, discover_decision: str, advice: dict | None = None) -> dict:
    name = product_name(brief)
    tailored = bool(advice and advice.get("source") == "model" and advice.get("price_points_eur_per_month"))
    prices = tuple(advice["price_points_eur_per_month"]) if tailored else TEST_PRICES_EUR
    why = (f"{advice['label']}: {advice.get('pricing_rationale') or ''} Anchor: {advice.get('price_anchor') or 'unknown'}"
           if tailored else "Test price only. No evidence yet that anyone would pay this.")
    options = [
        {"id": "free-core", "model": "Free core features", "price_eur_per_month": 0,
         "label": "ASSUMPTION", "why": "Lets interviewees try the concept; no paywall on the core job."},
    ] + [
        {"id": f"pro-{p}", "model": "Paid tier, monthly", "price_eur_per_month": p, "label": "ASSUMPTION",
         "why": why}
        for p in prices
    ]
    return {
        "product": name,
        "discover_decision": discover_decision,
        "options": options,
        "evidence": "None. Willingness to pay has not been measured (Lean Canvas: revenue streams UNKNOWN).",
        "test": ("Ask each interviewee what they spend today on the problem and at what monthly price the "
                 "product would be too expensive / a bargain; then a priced waitlist with no payment taken."),
        "pass_mark_to_set_before_testing": "e.g. at least 3 of 10 qualified interviewees accept the chosen test "
                                           "price (ASSUMPTION: the founder sets the real pass mark).",
        "price_source": (f"tailored by {advice['model']} from this brief and its evidence" if tailored
                         else "generic test grid (model not used)"),
        "founder_choice": None,
        "payments": "None. No payment provider, sandbox or card handling exists in this phase.",
    }


def product_name(brief: dict) -> str:
    """The founder's product name if the brief has one; otherwise a plain, honest placeholder."""
    return (brief.get("product_name") or "").strip() or f"Concept for {brief['target_customer']}"


def idea_phrase(brief: dict) -> str:
    """The idea as a phrase that reads correctly mid-sentence ("a browser extension that ...")."""
    idea = brief["idea"].strip().rstrip(".")
    return idea[:1].lower() + idea[1:] if idea[:2] in ("A ", "An") else idea


def pricing_markdown(p: dict) -> str:
    rows = "\n".join(f"| `{o['id']}` | {o['model']} | {o['price_eur_per_month']} | {o['label']} | {o['why']} |"
                     for o in p["options"])
    choice = (f"Founder-approved choice: **`{p['founder_choice']}`**." if p["founder_choice"]
              else "Founder choice: **not made yet** (requires founder approval).")
    return f"""# Phase 4, step 1: Pricing hypotheses

Product concept: {p['product']}. Discover gate: **{p['discover_decision']}**.

| Option | Model | EUR / month | Label | Why |
|---|---|---|---|---|
{rows}

- Evidence for any price: {p['evidence']}
- How to test: {p['test']}
- Pass mark to set before testing: {p['pass_mark_to_set_before_testing']}
- {p['payments']}

{choice}
"""


def policy_drafts(brief: dict) -> dict[str, str]:
    name = product_name(brief)
    values = "; ".join(brief.get("values_and_constraints", [])) or "none stated"
    terms = f"""# Phase 4, step 2: Terms of service (DRAFT)

> {DRAFT_BANNER}

1. **What this is.** {name} is an early-stage digital product offered by its founder. Features are
   described on the product page as proposals until they are delivered.
2. **No promises of results.** The product does not promise any business or time-saving outcome.
3. **Your account and content.** You keep ownership of anything you put into the product. You may
   delete it at any time.
4. **Acceptable use.** Do not use the product to break the law or to access data you are not allowed to
   see.
5. **Changes.** Material changes to these terms are announced to users before they apply.
6. **Contact.** A support address will be listed on the product page before launch.

Founder values carried into these terms: {values}.
"""
    privacy = f"""# Phase 4, step 2: Privacy policy (DRAFT)

> {DRAFT_BANNER}

- **Data collected:** only what the product needs to work, listed per feature before launch. No
  passwords or card numbers are stored by the product.
- **Purpose:** to provide the product. No sale of personal data; no advertising profiles.
- **Retention:** data is deleted when the user deletes it or closes the account.
- **Third parties:** none at draft stage. Any future processor must be listed here before it is used.
- **User rights:** access, correction, export and deletion on request.
- **Founder constraints applied:** {values}.
"""
    refund = f"""# Phase 4, step 2: Refund policy (DRAFT)

> {DRAFT_BANNER}

- Buyers can request a full refund within 14 days of purchase (ASSUMPTION: the founder may choose
  another period).
- A refund **revokes access** to the paid product; this is how the MOCKED delivery system behaves
  (`refunds.py`).
- Refunds are processed by the payment provider chosen at launch. VentureLab itself never holds,
  moves or refunds money.
"""
    for text in (terms, privacy, refund):
        check_content(text.replace("legal advice", "legal-advice"))  # banner names it; rules still apply
    return {"terms": terms, "privacy": privacy, "refund": refund}
