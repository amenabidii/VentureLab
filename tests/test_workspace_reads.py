"""Read-only endpoints added for the redesigned workspace: the run's brief and its journey.

Uses the STUBBED model and sources from conftest. Nothing here may write, approve or run a phase.
"""

from __future__ import annotations

import json
from pathlib import Path

from tests.test_integration_api import BRIEF, PROHIBITED, make, start
from tests.test_superseded_decisions import supersede


def test_brief_is_the_validated_founder_brief(tmp_path):
    api, svc, _ = make(tmp_path)
    run_id, _ = start(api, svc)
    b = api.get(f"/api/runs/{run_id}/brief").json()
    assert b["idea"] == BRIEF["idea"] and b["problem"] == BRIEF["problem"] and b["customer"] == BRIEF["customer"]
    assert b["hours"] == BRIEF["hours"] and b["budget"] == BRIEF["budget"] and b["currency"] == BRIEF["currency"]
    assert api.get("/api/runs/run-0000000000000000/brief").status_code == 404
    assert api.get("/api/runs/..%2F..%2Fx/brief").status_code == 404


def test_journey_reports_files_and_pending_without_side_effects(tmp_path):
    api, svc, _ = make(tmp_path)
    run_id, run = start(api, svc)
    before = sorted(p.relative_to(tmp_path).as_posix() for p in tmp_path.rglob("*") if p.is_file())
    log_before = svc.log_path.read_bytes()
    j = api.get(f"/api/runs/{run_id}/journey").json()
    assert j["available"] and j["discover"] == run["decision"] and j["runner"] == f"/phases/run/{run_id}"
    assert [p["phase"] for p in j["phases"]] == [2, 3, 4, 5, 6]
    assert all(p["files"] == [] and p["gates"] == [] for p in j["phases"])  # nothing generated by reading
    assert j["blocked"] is None and j["superseded"] is False
    after = sorted(p.relative_to(tmp_path).as_posix() for p in tmp_path.rglob("*") if p.is_file())
    assert svc.log_path.read_bytes() == log_before
    assert [f for f in after if f not in before and not f.startswith(".venturelab/")] == []


def test_journey_says_why_a_stop_or_superseded_run_is_blocked(tmp_path):
    api, svc, _ = make(tmp_path)
    stop_id, _ = start(api, svc, PROHIBITED)
    assert "STOP" in api.get(f"/api/runs/{stop_id}/journey").json()["blocked"]
    api2, svc2, _ = make(tmp_path / "second")
    run_id, _ = start(api2, svc2)
    supersede(svc2, run_id)
    j = api2.get(f"/api/runs/{run_id}/journey").json()
    assert j["superseded"] is True and "superseded" in j["blocked"]


def test_journey_rejects_malformed_or_unknown_runs(tmp_path):
    api, _, _ = make(tmp_path)
    assert api.get("/api/runs/not-a-run/journey").status_code == 404
    j = api.get("/api/runs/run-0000000000000000/journey").json()
    assert j["available"] is False and j["runner"] is None


